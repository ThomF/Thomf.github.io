import { createRequire } from 'module';
import http from 'http'; import fs from 'fs'; import path from 'path'; import os from 'os';
import { fileURLToPath } from 'url';
const require = createRequire(import.meta.url);
const { chromium } = require(path.join(os.homedir(), 'code/crate-digger/node_modules/playwright'));
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..'), PORT = 48124;
const shots = fs.mkdtempSync(path.join(os.tmpdir(), 'example-run-'));
const types={'.html':'text/html','.js':'text/javascript','.css':'text/css','.json':'application/json','.svg':'image/svg+xml'};
const srv=http.createServer((q,r)=>{let p=decodeURIComponent(q.url.split('?')[0].split('#')[0]);if(p==='/')p='/index.html';const f=path.join(ROOT,p);if(!f.startsWith(ROOT)||!fs.existsSync(f)||fs.statSync(f).isDirectory()){r.writeHead(404);return r.end();}r.writeHead(200,{'content-type':types[path.extname(f)]||'application/octet-stream'});fs.createReadStream(f).pipe(r);}).listen(PORT);
const base=`http://127.0.0.1:${PORT}`;
const fails=[];const chk=(c,m)=>{if(!c)fails.push(m);console.log('  ',c?'ok':'NO',m);};
const b=await chromium.launch();
for(const w of [1280,390]){
  console.log('width',w);
  const ctx=await b.newContext({viewport:{width:w,height:800},reducedMotion:'no-preference'});
  const pg=await ctx.newPage();const errs=[];
  pg.on('console',m=>{if(m.type()==='error')errs.push(m.text())});pg.on('pageerror',e=>errs.push(String(e)));
  await pg.goto(base+'/index.html');
  const hscroll=()=>pg.evaluate(()=>document.documentElement.scrollWidth>document.documentElement.clientWidth);
  const out=()=>pg.evaluate(()=>document.getElementById('sim-out').textContent);
  await pg.locator('#sim-out').scrollIntoViewIfNeeded();
  await pg.waitForFunction(()=>document.getElementById('sim-out').textContent.includes('add an admin panel'),null,{timeout:8000}).then(()=>chk(true,`${w} plays admin panel first`),()=>chk(false,`${w} plays admin panel first`));
  await pg.waitForFunction(()=>document.getElementById('sim-out').textContent.includes('[pilot]'),null,{timeout:30000}).then(()=>chk(true,`${w} reaches [pilot]`),()=>chk(false,`${w} reaches [pilot]`));
  chk((await pg.textContent('#sim-dir'))==='~/frisson',`${w} sim dir ~/frisson`);
  await pg.click('#sim-replay');
  await pg.waitForFunction(()=>document.getElementById('sim-out').textContent.includes('add dark mode toggle'),null,{timeout:8000}).then(()=>chk(true,`${w} run again -> dark mode`),()=>chk(false,`${w} run again -> dark mode`));
  const sum=pg.locator('details.harbor > summary');
  await sum.scrollIntoViewIfNeeded();
  chk(!(await pg.evaluate(()=>document.querySelector('details.harbor').open)),`${w} harbor closed initially`);
  await sum.click();
  chk(await pg.evaluate(()=>document.querySelector('details.harbor').open),`${w} harbor opens on click`);
  chk(await pg.locator('details.harbor .harbor__body').isVisible(),`${w} body visible`);
  chk(!(await hscroll()),`${w} index no hscroll, disclosure open`);
  await Promise.all([pg.waitForURL(/shipyard\.html#harbor$/),pg.click('details.harbor a')]);
  await pg.waitForTimeout(800);
  const r=await pg.evaluate(()=>{const e=document.getElementById('harbor').getBoundingClientRect();return {t:e.top,b:e.bottom,h:innerHeight}});
  chk(r.t<r.h&&r.b>0&&r.t>=-2,`${w} #harbor in view top=${Math.round(r.t)}`);
  await pg.waitForSelector('#app *',{timeout:5000});await pg.waitForTimeout(500);
  const txt=await pg.evaluate(()=>document.body.innerText);
  chk(/shipped/i.test(txt),`${w} renders shipped`);
  chk(/AC12/.test(txt),`${w} renders AC12`);
  chk(txt.includes('2026-11-09T06-16-12'),`${w} run id`);
  chk(await pg.locator('summary',{hasText:'Browser tester verdict'}).count()>0,`${w} Browser tester verdict summary`);
  chk(!(await hscroll()),`${w} shipyard.html no hscroll`);
  // harbor figure code block containment
  const fig=await pg.evaluate(()=>{const f=document.querySelector('#harbor figure');if(!f)return null;const vw=document.documentElement.clientWidth;return [...f.querySelectorAll('pre,code')].map(e=>{const x=e.getBoundingClientRect();return {tag:e.tagName,l:x.left,r:x.right,vw}})});
  chk(fig&&fig.length>0&&fig.every(x=>x.l>=-1&&x.r<=x.vw+1),`${w} harbor figure code inside screen ${JSON.stringify(fig&&fig.map(x=>[Math.round(x.l),Math.round(x.r)]))}`);
  await pg.locator('#harbor figure').scrollIntoViewIfNeeded();
  await pg.screenshot({path:path.join(shots,`harbor-${w}.png`)});
  chk(errs.length===0,`${w} no console errors ${JSON.stringify(errs)}`);
  await ctx.close();
}
await b.close();srv.close();
console.log('screenshots',shots);
console.log(fails.length?'FAIL AC7':'PASS AC7');
